  whyPoints: { t: string; d: string }[]
  /** 변화(결과) 섹션 제목 — [윗줄, 강조줄] (혜택/결과 중심, 상품별 차별화) */
  afterLine: string
  afterAccent: string
  /** 진행 후 변화 (Before → After, 감정적·구체적) */
  afters: DetailAfter[]
  /** 변화 섹션 마무리 한 줄 */
  afterClosing: string
  /** 취득/진행 시 얻는 실질 혜택 — 초중반에 '와닿게' 나열 */
