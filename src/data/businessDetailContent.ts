  /** '사실 대표님이 사는 것' 리프레임 — 표면 상품(취소선) */
  realBuyNot: string
  /** 리프레임 — 진짜 가치(명사구, 화면에서 '~입니다'로 이어짐) */
  realBuyIs: string
  /** 리프레임 보충 설명 1~2문장 */
  realBuyDesc: string
  /** '혼자 하기 어려운 이유' — 판단·구조 설계가 어려운 이유 3~4개 (01~04 번호 노출) */
  whyPoints: { t: string; d: string }[]
  /** 어려운 이유 섹션 마무리 — 상품별 미래AI랩 차별화 문장 (앰버 박스) */
  whyClosing: string
  /** (구버전 필드 — 현재 템플릿 미사용) */
  afterLine?: string
  afterAccent?: string
  afterClosing?: string
  /** 진행 전→후 변화 비교 (4개 이상) */
  afters: DetailAfter[]
  /** 혜택 카드 4~6개 — 체감 제목 + 작동 방식 + 실제 결과 (2~3문장) */
  benefits: DetailBenefit[]
  /** 혜택 섹션 하단 조건 안내문 (세제 등 — 미지정 시 공통 문구) */
  benefitsNote?: string
  /** 추천 대상 체크리스트 — 최근 실제 겪었을 상황·행동·불편 5개 이상 */
  checklist: string[]
  /** 진행 후 남는 것 — 그룹별 결과물 (공식/자산/다음단계) */
  outcomes: DetailOutcomeGroup[]
  /** 대행 비교 — 일반 대행 측 항목 */
  versusNormal: string[]
  /** 대행 비교 — 미래AI랩 측 항목 */
  versusOurs: string[]
  /** 대행 비교 마무리 강조 문장 (상품별) */
