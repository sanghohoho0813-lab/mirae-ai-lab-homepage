export type DetailCase = {
  /** talk = 카톡 알림톡형, doc = 문서/구성 예시형 */
  style: 'talk' | 'doc'
  /** 카드 위 대형 헤드라인 (예: '1억원 진행 예시') — 파랑 강조 부분 */
  bigAccent: string
  /** 헤드라인 뒷부분 (예: '진행 예시') */
  bigRest: string
  /** 카드 제목 (예: '[○○은행] 대출 실행 안내') */
  title: string
  sub?: string
  rows: { k: string; v: string }[]
  boxLabel: string
  boxValue: string
}

// 손실 카드 — 역할 분담(돈/시간/기회 등). tag = 손실 종류 라벨(붉은색 소제목).
export type DetailLoss = { icon: string; tag: string; t: string; d: string }
export type DetailAfter = { before: string; after: string }
export type DetailBenefit = { icon: string; t: string; d: string }
/** 결과물 그룹 — 공식 결과물 / 회사 자산 / 다음 단계 등 (단순 파일 목록 금지) */
export type DetailOutcomeGroup = { label: string; icon: string; items: string[] }

export type DetailContent = {
  emoji: string
  hookLine: string
  hookAccent: string
  hookSub: string
  pains: string[]
  /** 손실 섹션 제목 — 상품별 날카로운 한 문장. [앞부분(남색), 강조부분(붉은색)] */
  lossLine: string
  lossAccent: string
  /** 지금 미루면 쌓이는 손실 3개 — 돈/시간/기회로 역할 분담(각 카드에 손실 tag) */
  losses: DetailLoss[]
  /** 손실 섹션 마무리 한 줄 (테두리 박스 · 상품별 대표 공포 종합) */
  lossClosing: string
  /** '사실 대표님이 사는 것' 리프레임 — 표면 상품(취소선) */
  realBuyNot: string
  /** 리프레임 — 진짜 가치(명사구, 화면에서 '~입니다'로 이어짐) */
  realBuyIs: string
  /** 리프레임 보충 설명 1~2문장 */
  realBuyDesc: string
  /** '혼자 하기 어려운 이유' — 판단·구조 설계가 어려운 이유 3~4개 (01~04 번호 노출) */
  whyPoints: { t: string; d: string }[]
  /** 어려운 이유 섹션 마무리 — 상품별 미래AI랩 차별화 문장 (앰버 박스) */
  whyClosing: string
  /** (구버전 필드 — 현재 템플릿 미사용) */
  afterLine?: string
  afterAccent?: string
  afterClosing?: string
  /** 진행 전→후 변화 비교 (4개 이상) */
  afters: DetailAfter[]
  /** 혜택 카드 4~6개 — 체감 제목 + 작동 방식 + 실제 결과 (2~3문장) */
  benefits: DetailBenefit[]
  /** 혜택 섹션 하단 조건 안내문 (세제 등 — 미지정 시 공통 문구) */
  benefitsNote?: string
  /** 추천 대상 체크리스트 — 최근 실제 겪었을 상황·행동·불편 5개 이상 */
  checklist: string[]
  /** 진행 후 남는 것 — 그룹별 결과물 (공식/자산/다음단계) */
  outcomes: DetailOutcomeGroup[]
  /** 대행 비교 — 일반 대행 측 항목 */
  versusNormal: string[]
  /** 대행 비교 — 미래AI랩 측 항목 */
  versusOurs: string[]
  /** 대행 비교 마무리 강조 문장 (상품별) */
  versusClosing: string
  reasons: string[]
  casesKicker: string
  casesTitle: string
  casesAccent: string
  cases: DetailCase[]
}

