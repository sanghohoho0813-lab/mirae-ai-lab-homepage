export type DetailCase = {
  /** talk = 카톡 알림톡형, doc = 문서/구성 예시형 */
  style: 'talk' | 'doc'
  /** 카드 위 대형 헤드라인 (예: '1억원 진행 예시') — 파랑 강조 부분 */
  bigAccent: string
  /** 헤드라인 뒷부분 (예: '진행 예시') */
  bigRest: string
  /** 카드 제목 (예: '[○○은행] 대출 실행 안내') */
  title: string
  sub?: string
  rows: { k: string; v: string }[]
  boxLabel: string
  boxValue: string
}

// 손실 카드 — 역할 분담(돈/시간/기회 등). tag = 손실 종류 라벨(붉은색 소제목).
