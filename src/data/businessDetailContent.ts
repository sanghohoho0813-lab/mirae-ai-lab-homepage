export type DetailAfter = { before: string; after: string }
export type DetailBenefit = { icon: string; t: string; d: string }

export type DetailContent = {
  emoji: string
  hookLine: string
  hookAccent: string
  hookSub: string
  pains: string[]
  /** 손실 섹션 제목 — 상품별 날카로운 한 문장. [앞부분(남색), 강조부분(붉은색)] */
  lossLine: string
  lossAccent: string
  /** 지금 미루면 쌓이는 손실 3개 — 돈/시간/기회로 역할 분담(각 카드에 손실 tag) */
  losses: DetailLoss[]
  /** 손실 섹션 마무리 한 줄 (테두리 박스 · 상품별 대표 공포 종합) */
  lossClosing: string
  /** '사실 대표님이 사는 것' 리프레임 — 표면 상품(취소선) */
  realBuyNot: string
  /** 리프레임 — 진짜 가치(명사구, 화면에서 '~입니다'로 이어짐) */
  realBuyIs: string
  /** 리프레임 보충 설명 1~2문장 */
  realBuyDesc: string
  whyPoints: { t: string; d: string }[]
  /** 변화(결과) 섹션 제목 — [윗줄, 강조줄] (혜택/결과 중심, 상품별 차별화) */
  afterLine: string
  afterAccent: string
  /** 진행 후 변화 (Before → After, 감정적·구체적) */
  afters: DetailAfter[]
  /** 변화 섹션 마무리 한 줄 */
  afterClosing: string
  /** 취득/진행 시 얻는 실질 혜택 — 초중반에 '와닿게' 나열 */
  benefits: DetailBenefit[]
  reasons: string[]
  casesKicker: string
  casesTitle: string
  casesAccent: string
  cases: DetailCase[]
}

