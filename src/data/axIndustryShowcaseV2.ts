export const AX_V2_STAGE_LABELS = ['운영 손실 발견', '오늘의 실행', '매출 기회', '반복매출', '실제 활용 예시'] as const
export type AxV2StageNo = 1 | 2 | 3 | 4 | 5

export type AxV2Image = { src: string; srcSm: string; w: number; h: number; alt: string }

export type AxV2Stage = {
  no: AxV2StageNo
  /** 단계 이름 — 5개 업종 공통 서사 */
  label: string
  /** 이미지에 인쇄된 헤드라인을 웹 호흡으로 다듬은 한 줄 */
  title: string
  /** 최대 두 줄 설명 */
  desc: string
  /** 이미지 하단 기능 칩 */
  chips: string[]
  img: AxV2Image
}

export type AxV2Idea = {
  no: 1 | 2
  /** 고객이 바로 이해할 수 있는 아이디어명 */
  name: string
  /** 현재 문제 1~2줄 */
  problem: string
  /** 적용 후 고객이 할 수 있는 행동 3~5개 */
  actions: string[]
  /** 새로운 매출구조 3개 */
  revenues: string[]
  /** 정책자금 설명 포인트 1줄 */
  policyPoint: string
  /** 관련 태그 최대 3개 */
  tags: string[]
}

export type AxV2Industry = {
  id: string
  slug: string
  displayName: string
  icon: string
  /** 업종 버튼 아래 한 줄 훅 */
  shortHook: string
  /** 업종 Hero 아래 2~3줄 개요 */
  overview: string
  /** 시연 화면에 쓰인 가상 브랜드명 */
  demoBrand: string
  stages: AxV2Stage[]
  ideas: AxV2Idea[]
  /** 업무별 보기 연결 태그 */
  taskTags: string[]
  /** 이 업종의 화면이 정책자금 심사에서 설명하는 사업구조 */
  policyPoint: string
  targetCustomer: string
  seoTitle: string
  seoDescription: string
}

const W = 1672
const H = 941

type StageSeed = { title: string; desc: string; chips: string[] }

function buildStages(slug: string, displayName: string, seeds: [StageSeed, StageSeed, StageSeed, StageSeed, StageSeed]): AxV2Stage[] {
  return seeds.map((s, i) => {
    const no = (i + 1) as AxV2StageNo
    const label = AX_V2_STAGE_LABELS[i]
    const base = `/ax-industries/${slug}/0${no}`
    return {
      no,
      label,
      title: s.title,
      desc: s.desc,
      chips: s.chips,
      img: {
        src: `${base}.webp`,
        srcSm: `${base}-sm.webp`,
        w: W,
        h: H,
        alt: `${displayName} AX ${no}단계 ${label} 화면 — ${s.title}`,
      },
    }
  })
}

